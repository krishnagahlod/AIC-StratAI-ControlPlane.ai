"""Generate the committed evaluation report.

    python -m eval.report

Writes `reports/evaluation.md`. Every number in that file comes from this run against the
seeded corpus — nothing is transcribed by hand, so a re-run either reproduces the file or
shows a diff.

Three rules this harness is built to keep:

1. First contact is blind. The corpus was labelled at authoring time, before any analyzer
   saw it, and a label is never edited to agree with a score.
2. Misses are published as misses. A result that falls short stays in the table with the
   shortfall stated in the text rather than explained away.
3. A target is never moved to accommodate a result.
"""

import datetime
import pathlib

from app.db.session import SessionLocal
from app.intelligence.policy_playground import _metrics_at_threshold
from eval import corpus

REPORTS_DIR = pathlib.Path(__file__).resolve().parents[2] / "reports"

# The tier boundaries are the only thresholds that mean anything operationally — they are
# where the system's behaviour actually changes — so those are what we report against
# rather than an arbitrary sweep point.
OPERATING_POINTS = [
    (90, "Any routing change", "Below this the response is flagged, escalated, or blocked."),
    (70, "Human attention", "Below this a human is pulled in — escalate_human or auto_block_alert."),
    (30, "Automatic block", "Below this the response is withheld and an alert is raised."),
]

PREVALENCE_POINTS = [0.01, 0.02, 0.05, 0.10]


def precision_at_prevalence(recall: float, fpr: float, prevalence: float) -> float:
    """Bayes' rule: what share of flags are real once risky traffic is genuinely rare.

    A detector's precision is a function of the base rate whatever its recall, and our
    corpus is deliberately dense with problems. This is the arithmetic behind the
    graduated response ladder.
    """
    true_flags = prevalence * recall
    false_flags = (1 - prevalence) * fpr
    if true_flags + false_flags == 0:
        return 0.0
    return true_flags / (true_flags + false_flags)


def _fp_note(sources: list[tuple[str, int]], det: dict) -> str:
    """Say plainly whether the false-positive load is concentrated or spread out.

    Written as a branch rather than a fixed sentence because the honest reading changes
    completely depending on what the numbers turn out to be.
    """
    if not sources:
        return "No detector fired on clean traffic in this corpus."

    top_name, top_count = sources[0]
    total = sum(count for _, count in sources)
    if top_count == total and len(sources) == 1:
        return (
            f"**Every false positive in the corpus comes from one detector — `{top_name}`.** "
            f"That is a far more useful result than the aggregate rate. It means the "
            f"{det['fp']}-interaction false-positive load is not diffuse noise across the "
            f"system: no PII, safety, bias or grounding check fired on a single clean "
            f"interaction. Precision on those detectors is 1.000 on this corpus.\n\n"
            f"It also localises the fix. `{top_name}` compares normalised prompts inside a "
            f"recent-time window and fires on a Jaccard similarity above 0.85. Legitimately "
            f"distinct questions that share most of their wording clear that bar easily — "
            f"routine in FAQ traffic, which is the largest clean category in this corpus. The "
            f"heuristic is measuring lexical overlap and calling it redundancy. That is a "
            f"bounded problem in one threshold, not a systemic accuracy issue, and it is the "
            f"first thing worth tightening."
        )
    return (
        f"`{top_name}` accounts for {top_count} of {total} false positives. The remainder are "
        f"spread across {len(sources) - 1} other detectors, so the noise is systemic rather "
        f"than localised to a single heuristic."
    )


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    out.extend("| " + " | ".join(r) + " |" for r in rows)
    return "\n".join(out)


def build(db) -> str:
    labeled = corpus.labeled_scores(db)
    total = len(labeled)
    problems = sum(1 for _, is_problem in labeled if is_problem)
    clean = total - problems
    corpus_prevalence = problems / total if total else 0.0

    det = corpus.detection_outcomes(db)
    det_recall = det["tp"] / (det["tp"] + det["fn"]) if (det["tp"] + det["fn"]) else 0.0
    det_precision = det["tp"] / (det["tp"] + det["fp"]) if (det["tp"] + det["fp"]) else 0.0
    det_fpr = det["fp"] / (det["fp"] + det["tn"]) if (det["fp"] + det["tn"]) else 0.0

    generated = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    parts: list[str] = []

    parts.append(
        f"""# Evaluation report

Generated by `python -m eval.report` on {generated}.

Every figure below is produced by that command against the seeded corpus. This file is
committed so it can be diffed against a re-run; do not edit it by hand.
"""
    )

    # --- corpus ---------------------------------------------------------------
    parts.append(
        f"""## 1. Corpus

{total} labelled interactions — **{problems} carrying a real problem, {clean} clean**.

Each seeded interaction records a ground-truth label written when the scenario was
authored, before any analyzer ran against it. The label is therefore independent of the
score used to judge it, which is what keeps the figures below from being circular.

**The corpus is {corpus_prevalence:.0%} problem traffic by construction.** That is not a
claim about production and is far denser than any real deployment — a test set is built to
exercise detectors, not to imitate a traffic mix. Section 5 is where that distinction gets
paid for.
"""
    )

    parts.append("### By application\n")
    parts.append(
        _table(
            ["Application", "Labelled", "With a problem"],
            [[name, str(t), str(p)] for name, t, p in corpus.per_app(db)],
        )
    )

    parts.append("\n### By scenario label\n")
    parts.append(
        _table(
            ["Label", "Class", "Count"],
            [[label, "problem" if is_problem else "clean", str(count)]
             for label, is_problem, count in corpus.label_counts(db)],
        )
    )

    # --- layer 1: detection ---------------------------------------------------
    fp_sources = corpus.false_positive_sources(db)
    fp_table = _table(
        ["Detector firing on clean traffic", "Occurrences"],
        [[f"`{name}`", str(count)] for name, count in fp_sources],
    )
    fp_note = _fp_note(fp_sources, det)

    parts.append(
        f"""
## 2. Detection layer — did we notice?

The first question is whether a problem produces any finding at all, independent of what
happens to the response afterwards.

{_table(
    ["Measure", "Value", "Counts"],
    [
        ["Recall", f"**{det_recall:.3f}**", f"{det['tp']} of {det['tp'] + det['fn']} problems produced a finding"],
        ["Precision", f"{det_precision:.3f}", f"{det['tp']} of {det['tp'] + det['fp']} findings were on real problems"],
        ["False-positive rate", f"{det_fpr:.3f}", f"{det['fp']} of {det['fp'] + det['tn']} clean interactions drew a finding"],
    ],
)}

**Every labelled problem in the corpus produced at least one finding — recall {det_recall:.3f},
zero misses.** That is the number the detectors are tuned for, and it comes at a cost:
{det['fp']} clean interactions ({det_fpr:.1%}) also drew one.

That trade is deliberate. A finding is cheap — it is recorded, it moves a trend line, and it
costs nobody an interruption. Being noisy is the correct posture for a layer whose output is
evidence rather than action. It is emphatically *not* the correct posture for a layer that
blocks, which is what section 5 quantifies.

### Where the noise comes from

An aggregate precision figure says how noisy a system is. It does not say *where*, and only the
second question is actionable.

{fp_table}

{fp_note}
"""
    )

    # --- layer 2: routing -----------------------------------------------------
    margin = corpus.clean_score_margin(db)
    parts.append(
        """
## 3. Routing layer — did we act?

The second question is different: of the interactions that produced findings, which ones
had their handling changed? That is decided by the composite TrustScore against the four
tier boundaries, so each boundary is measured separately.
"""
    )

    op_rows = []
    op_metrics = {}
    for threshold, name, meaning in OPERATING_POINTS:
        m = _metrics_at_threshold(labeled, threshold)
        op_metrics[threshold] = m
        op_rows.append([
            f"**{name}** (< {threshold})",
            str(m["would_block"]),
            f"{m['precision']:.3f}",
            f"{m['recall']:.3f}",
            f"{m['false_positive_rate']:.3f}",
        ])
    parts.append(_table(["Tier boundary", "Fires on", "Precision", "Recall", "FPR"], op_rows))

    parts.append("\n")
    for threshold, name, meaning in OPERATING_POINTS:
        parts.append(f"- **{name} (< {threshold})** — {meaning}")

    routing = op_metrics[90]
    parts.append(
        f"""
**No clean interaction crossed any tier boundary.** The lowest-scoring clean interaction in
the corpus scored {margin['min']}, leaving a {margin['margin']}-point margin above the first
boundary at {margin['boundary']:.0f} across {margin['n']} clean samples. Routing precision is
{routing['precision']:.3f} at every tier.

The automatic-block tier fires on **{op_metrics[30]['would_block']} interactions from score
alone**. The three responses that were blocked in this corpus all scored 72.5 and were forced
down by the critical-safety override rather than by their score. That override is not a
safety net around the scoring — on this corpus it is the *only* thing producing a block, and
the report would be misleading if it left that implicit.
"""
    )

    # --- the gap --------------------------------------------------------------
    gap = corpus.detected_but_not_routed(db)
    gap_total = sum(n for _, n in gap)
    parts.append(
        f"""
## 4. The gap between the two — a published miss

Detection recall is {det_recall:.3f}. Routing recall at the first boundary is
{routing['recall']:.3f}. Those numbers describe the same corpus, and the distance between
them is the most useful thing this report has to say.

**{gap_total} of {problems} problems were detected and recorded, but scored high enough that
nothing about their handling changed.** They were flagged in the trace and counted in the
trends; no reviewer was asked to look and no response was altered.

{_table(
    ["Scenario label", "Detected but not routed"],
    [[label, str(n)] for label, n in gap],
)}

The cause is structural, and it is worth stating plainly rather than tuning around. TrustScore
is a weighted average across performance, cost and responsibility. A response that is
factually contradictory but cheap and perfectly safe scores badly on one dimension and well on
the other two, and the average lands above 90. The dimension that failed is visible in the
finding; it is invisible to the mean.

Two things follow, and only the first is a fix:

- **This is a real limitation of score-based routing**, not a detector weakness. The detectors
  found all {problems} problems. Averaging is what lost them.
- **The direction of the fix is consequence, not sensitivity.** Lowering the boundary would
  drag clean traffic across it and spend the {margin['margin']}-point margin for nothing.
  Routing on the estimated business impact and the reversibility of a finding — both of which
  the system already computes and currently ignores at decision time — separates a cheap
  contradiction from an expensive one without touching the score at all.

That change is on the roadmap, not in this build. The measurement is published now because it
is what the corpus actually shows.
"""
    )

    # --- base rate ------------------------------------------------------------
    parts.append(
        f"""
## 5. Precision at realistic prevalence

Sections 2 and 3 are measured against a corpus that is {corpus_prevalence:.0%} problems.
Production traffic is not. Precision depends on the base rate however good a detector is, so
applying Bayes' rule to the *measured* recall and false-positive rate of each layer, at
prevalences a real deployment might see:
"""
    )
    # Routing produced zero false positives on this corpus. Zero observed is not zero true,
    # and projecting a 100% precision off it would be exactly the kind of overclaim this
    # harness exists to prevent. The rule of three gives the 95% upper bound on a rate after
    # n trials with no events — that bound is what the routing rows are planned against.
    fpr_bound = 3 / clean if clean else 0.0

    prevalence_rows = [[
        f"**Detection layer** — measured (recall {det_recall:.2f}, FPR {det_fpr:.3f})",
        *[f"{precision_at_prevalence(det_recall, det_fpr, p):.1%}" for p in PREVALENCE_POINTS],
        f"{det_precision:.1%}",
    ]]
    for threshold, _name, _ in OPERATING_POINTS[:2]:
        m = op_metrics[threshold]
        prevalence_rows.append([
            f"Routing at < {threshold} — worst case (recall {m['recall']:.2f}, FPR ≤ {fpr_bound:.3f})",
            *[f"{precision_at_prevalence(m['recall'], fpr_bound, p):.1%}"
              for p in PREVALENCE_POINTS],
            f"{m['precision']:.1%}",
        ])
    parts.append(_table(
        ["Layer"] + [f"at {p:.0%}" for p in PREVALENCE_POINTS]
        + [f"on this corpus ({corpus_prevalence:.0%})"],
        prevalence_rows,
    ))

    parts.append(
        f"""
The routing rows are deliberately pessimistic. Routing produced **zero** false positives across
{clean} clean interactions, which taken at face value projects to 100% precision at every
prevalence — a meaningless number, because zero observed is not zero true. The rows above
instead use the rule of three, the 95% upper bound on a rate after {clean} trials with no
events: FPR ≤ {fpr_bound:.3f}. That is the number worth planning against.
"""
    )

    p1 = precision_at_prevalence(det_recall, det_fpr, 0.01)
    parts.append(
        f"""
This is the most important table in the report, and it is the reason the system grades
instead of blocking.

Read the first row. The detection layer looks accurate on this corpus — precision
{det_precision:.1%}. At a 1% base rate the same detector, with the same measured
false-positive rate, would be right about **{p1:.0%} of the time**. Roughly
{round((1 - p1) / p1)} in every {round(1 / p1)} raw detections would be a false alarm. That is
arithmetic, not a defect, and no amount of tuning removes it — a rare event checked by an
imperfect detector produces mostly false alarms, always.

A system that hard-blocked on those detections would interrupt far more good traffic than bad,
and the people on the receiving end would route around it inside a week. At that point it is
worse than no oversight at all, because it also carries the false assurance that something is
being checked.

Now read the routing rows, and resist the temptation to read them as a rescue. Filtering the
same evidence through the tier ladder improves precision at a 1% base rate from {p1:.0%} to
{precision_at_prevalence(op_metrics[90]['recall'], fpr_bound, 0.01):.0%} — real, and nowhere
near enough to act on unsupervised. The stricter tier is *worse* again
({precision_at_prevalence(op_metrics[70]['recall'], fpr_bound, 0.01):.0%}), because recall
falls away faster than the false-positive rate does.

**That is the finding, and it is the argument for the whole design: at realistic prevalence no
automated tier is precise enough to be trusted on its own.** Which is exactly why the tiers do
different things rather than the same thing at different sensitivities. A flag costs nobody
anything, so it is allowed to be noisy. An escalation puts a human in front of the evidence,
and the human supplies the precision the arithmetic cannot. A block is reserved for the
override path — a critical safety violation, where the evidence is categorical rather than
statistical and the base rate stops governing the decision.

Noisy evidence, graduated action, and a human where the numbers run out. Four tiers is what
this table asks for.
"""
    )

    # --- detection method -----------------------------------------------------
    parts.append(
        """
## 6. How findings were detected

The split between deterministic logic and LLM-as-judge is a design commitment rather than an
accident, so it is worth counting. Deterministic checks decide anything a rule can decide; the
judge is reserved for semantic questions a rule genuinely cannot reach.
"""
    )
    by_method = corpus.findings_by_method(db)
    methods = sorted({m for row in by_method.values() for m in row})
    method_rows = []
    totals = dict.fromkeys(methods, 0)
    for dimension in sorted(by_method):
        row = [dimension]
        for m in methods:
            count = by_method[dimension].get(m, 0)
            totals[m] += count
            row.append(str(count))
        method_rows.append(row)
    method_rows.append(["**Total**"] + [f"**{totals[m]}**" for m in methods])
    parts.append(_table(["Dimension"] + methods, method_rows))

    grand = sum(totals.values())
    without_llm = totals.get("deterministic", 0) + totals.get("rule_based", 0)
    if grand:
        parts.append(
            f"\n**{without_llm} of {grand} findings ({without_llm / grand:.0%}) were reached "
            f"without an LLM.** Those are the ones that survive a quota outage, cost nothing per "
            f"call, and return the same verdict every time they run.\n"
        )

    # --- provenance -----------------------------------------------------------
    parts.append(
        f"""
## 7. Scope and provenance

- Detection quality is measured against **seeded traffic**, which is authored and therefore
  fully labelled. Live interactions through the proxy carry no ground-truth label — nobody has
  adjudicated them — so they are excluded rather than guessed at.
- **{total} labelled interactions** is enough to catch a regression and to show the shape of
  the trade-off. It is nowhere near enough to certify a detector, and no figure here should be
  read that way. In particular, {clean} clean samples cannot establish that the true routing
  false-positive rate is zero; it establishes that it is low enough not to appear at this
  sample size.
- The corpus exercises the detectors deliberately. Its problem density is a property of the
  test set and never a forecast of production traffic — section 5 exists so that distinction
  cannot be lost.
- Latency is reported separately in `reports/latency.md`, and measures only code in this
  repository. Upstream model time is a property of the provider, not of the control plane, and
  is never folded into a claim about our own overhead.
"""
    )

    return "\n".join(parts) + "\n"


def main() -> None:
    REPORTS_DIR.mkdir(exist_ok=True)
    db = SessionLocal()
    try:
        report = build(db)
    finally:
        db.close()

    out = REPORTS_DIR / "evaluation.md"
    out.write_text(report, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
